using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CsTranspiler;

/// <summary>A compiler or transpiler message, Roslyn style.</summary>
public sealed record Diag(string File, int Line, int Column, string Severity, string Code, string Message)
{
    public override string ToString() => $"{File}({Line},{Column}): {Severity} {Code}: {Message}";
}

public sealed class FileOutput
{
    public string CsPath = "";
    public string TsPath = "";
    public string Ts = "";
    public bool HasErrors;
}

public sealed class CompileResult
{
    public List<Diag> Diagnostics = new();
    public List<FileOutput> Files = new();
    /// <summary>.ts files written (changed).</summary>
    public List<string> Written = new();
    public List<string> Unchanged = new();
    /// <summary>.ts files kept as they were because their .cs has errors.</summary>
    public List<string> Kept = new();
    /// <summary>Generated .ts files whose .cs no longer exists.</summary>
    public List<string> Orphans = new();
    public long Ms;
}

/// <summary>
/// The C# project of a Cocos project: every .cs under assets/, compiled with Roslyn against
/// the Cocos bindings, then emitted as one .ts per .cs. Trees are cached by write time, so
/// the server only re-parses what changed.
/// </summary>
public sealed class Workspace
{
    public const string Header = "// <auto-generated> from {0} by the C# extension. Edit the .cs file: this file is overwritten.";
    public const string HeaderPrefix = "// <auto-generated> from ";

    static ImmutableArray<MetadataReference> _refs;
    static string _globalUsings;
    readonly Dictionary<string, (DateTime time, long size, SyntaxTree tree)> _trees = new(StringComparer.OrdinalIgnoreCase);
    static readonly CSharpParseOptions ParseOptions = new(LanguageVersion.Latest, DocumentationMode.None);

    /// <summary>Warnings that are noise for Cocos scripts (fields assigned by the engine, hiding lifecycle methods...).</summary>
    static readonly string[] Silenced = { "CS0108", "CS0114", "CS0169", "CS0649", "CS0414", "CS0067", "CS8618", "CS0659", "CS0661", "CS0660", "CS1998", "CS8019", "CS0105", "CS0219" };

    public static string ToolDir => AppContext.BaseDirectory;

    static ImmutableArray<MetadataReference> References()
    {
        if (!_refs.IsDefault) return _refs;
        var list = new List<MetadataReference>();
        var tpa = (AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") as string ?? "").Split(Path.PathSeparator);
        foreach (var p in tpa)
        {
            var n = Path.GetFileNameWithoutExtension(p);
            if (n == "System.Runtime" || n == "System.Private.CoreLib" || n == "System.Collections" || n == "System.Console" || n == "System.Linq" ||
                n == "Microsoft.CSharp" || n == "System.Threading.Tasks" || n == "System.Runtime.Extensions" || n == "netstandard" || n == "System.Diagnostics.Debug" ||
                n == "System.Threading" || n == "System.Collections.Concurrent" || n == "System.Linq.Expressions" || n == "System.ObjectModel")
                list.Add(MetadataReference.CreateFromImage(File.ReadAllBytes(p)));
        }
        // read into memory: the dll stays free to be rebuilt
        list.Add(MetadataReference.CreateFromImage(File.ReadAllBytes(Path.Combine(ToolDir, "Cocos.Bindings.dll"))));
        _refs = list.ToImmutableArray();
        return _refs;
    }

    /// <summary>The TS interop stubs (temp/csharp/TsBindings.g.cs), or an empty one.</summary>
    public const string TsBindingsRel = "temp/csharp/TsBindings.g.cs";
    const string EmptyTsBindings = "// <auto-generated> no TypeScript exports bound yet\npublic static partial class ProjectExports { }\n";
    (string path, DateTime time, long size, SyntaxTree tree) _ts;
    static SyntaxTree _emptyTs;

    SyntaxTree TsTree(string root)
    {
        var path = root == null ? null : Path.GetFullPath(Path.Combine(root, TsBindingsRel));
        if (path != null && File.Exists(path))
        {
            var info = new FileInfo(path);
            if (_ts.tree != null && _ts.path == path && _ts.time == info.LastWriteTimeUtc && _ts.size == info.Length) return _ts.tree;
            var tree = CSharpSyntaxTree.ParseText(File.ReadAllText(path), ParseOptions, path, Encoding.UTF8);
            _ts = (path, info.LastWriteTimeUtc, info.Length, tree);
            return tree;
        }
        return _emptyTs ??= CSharpSyntaxTree.ParseText(EmptyTsBindings, ParseOptions, "TsBindings.g.cs");
    }

    static SyntaxTree _usingsFor;
    static string _usingsText;

    /// <summary>
    /// Global usings with the project's TypeScript: its types are in the global namespace (no using
    /// needed, and they win over cc's, like C# classes of the project), its functions and variables in
    /// `using static ProjectExports`. Extensions (Ext.TweenPro...) are never global: scripts add
    /// `using Ext.TweenPro;`. A cc alias (EventHandler...) is left out when the project has that name.
    /// </summary>
    public static string GlobalUsings(SyntaxTree tsTree)
    {
        if (tsTree == _usingsFor && _usingsText != null) return _usingsText;
        var globalTypes = GlobalTypeNames(tsTree);
        var sb = new StringBuilder();
        foreach (var line in GlobalUsings().Split('\n'))
        {
            var m = System.Text.RegularExpressions.Regex.Match(line, @"^global using (\w+) = ");
            if (line.Length > 0 && !(m.Success && globalTypes.Contains(m.Groups[1].Value))) sb.Append(line).Append('\n');
        }
        sb.AppendLine("global using static ProjectExports;");
        _usingsFor = tsTree;
        _usingsText = sb.ToString();
        return _usingsText;
    }

    public string GlobalUsingsFor(string root) => GlobalUsings(TsTree(root));

    /// <summary>Types declared at the top level of a tree (the global namespace).</summary>
    static HashSet<string> GlobalTypeNames(SyntaxTree tree) =>
        new(((CompilationUnitSyntax)tree.GetRoot()).Members.OfType<BaseTypeDeclarationSyntax>().Select(t => t.Identifier.ValueText), StringComparer.Ordinal);

    /// <summary>
    /// The stubs without the project TypeScript types a C# script of the project also declares in the
    /// global namespace: the C# one wins (two definitions would not compile).
    /// </summary>
    (SyntaxTree tree, List<string> hidden) WithoutUserTypes(SyntaxTree tsTree, List<SyntaxTree> userTrees)
    {
        var user = new HashSet<string>(StringComparer.Ordinal);
        foreach (var t in userTrees) user.UnionWith(GlobalTypeNames(t));
        var root = (CompilationUnitSyntax)tsTree.GetRoot();
        var hidden = root.Members.OfType<BaseTypeDeclarationSyntax>().Where(t => user.Contains(t.Identifier.ValueText)).ToList();
        if (hidden.Count == 0) return (tsTree, new List<string>());
        var key = string.Join(",", hidden.Select(h => h.Identifier.ValueText));
        if (_filtered.source == tsTree && _filtered.key == key) return (_filtered.tree, _filtered.names);
        var tree = tsTree.WithRootAndOptions(root.RemoveNodes(hidden, SyntaxRemoveOptions.KeepNoTrivia), tsTree.Options);
        var names = hidden.Select(h => h.Identifier.ValueText).ToList();
        _filtered = (tsTree, key, tree, names);
        return (tree, names);
    }

    (SyntaxTree source, string key, SyntaxTree tree, List<string> names) _filtered;

    /// <summary>Where the stubs declare each type and each exported function: for hints on errors.</summary>
    static (Dictionary<string, List<string>> types, Dictionary<string, List<string>> members) StubIndex(SyntaxTree tsTree)
    {
        var types = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        var members = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        void Add(Dictionary<string, List<string>> d, string k, string v)
        {
            if (!d.TryGetValue(k, out var l)) d[k] = l = new List<string>();
            if (!l.Contains(v)) l.Add(v);
        }
        foreach (var t in tsTree.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
        {
            if (t.Parent is not BaseNamespaceDeclarationSyntax ns) continue;
            var nsName = ns.Name.ToString();
            Add(types, t.Identifier.ValueText, nsName);
            if (t is ClassDeclarationSyntax c && c.Modifiers.Any(SyntaxKind.StaticKeyword))
                foreach (var m in c.Members)
                {
                    var mn = m switch { MethodDeclarationSyntax md => md.Identifier.ValueText, PropertyDeclarationSyntax pd => pd.Identifier.ValueText, _ => null };
                    if (mn != null) Add(members, mn, nsName + "." + c.Identifier.ValueText);
                }
        }
        return (types, members);
    }

    /// <summary>
    /// A hint after the errors the namespaces cause: an ambiguous name (cc.Input and
    /// Ext.InputSystem.Input), or a name only an extension namespace has (missing using).
    /// </summary>
    static string Hint(Diagnostic d, (Dictionary<string, List<string>> types, Dictionary<string, List<string>> members) index)
    {
        var msg = d.GetMessage(System.Globalization.CultureInfo.InvariantCulture);
        if (d.Id == "CS0104")
        {
            var m = System.Text.RegularExpressions.Regex.Match(msg, @"'([^']+)' is an ambiguous reference between '([^']+)' and '([^']+)'");
            if (!m.Success) return null;
            var name = m.Groups[1].Value;
            var both = new[] { m.Groups[2].Value, m.Groups[3].Value };
            // an extension's name over cc's; cc's over System's (EventHandler, ValueType)
            var pick = both.FirstOrDefault(x => x.StartsWith("Ext.")) ?? both.FirstOrDefault(x => x.StartsWith("cc.")) ?? m.Groups[3].Value;
            var ns = pick.Substring(0, Math.Max(0, pick.LastIndexOf('.')));
            // an attribute: [ReadOnly] between cc.ReadOnlyAttribute and Ext.AdvancedInspector.ReadOnlyAttribute
            if (pick.EndsWith("Attribute") && !name.EndsWith("Attribute"))
                return $"Write [{ns}.{name}], or add `using X = {ns};` and write [X.{name}].";
            return $"Write {pick}, or add `using {name} = {pick};` at the top of the file.";
        }
        if (d.Id == "CS0616")
        {
            // [Button] without its using: cc.Button is found, and it is no attribute
            var m = System.Text.RegularExpressions.Regex.Match(msg, @"^'([^']+)' is not an attribute class");
            if (m.Success && index.types.TryGetValue(m.Groups[1].Value.Split('.').Last() + "Attribute", out var homes))
                return "The attribute is in " + string.Join(" and ", homes) + ": add `using " + homes[0] + ";`.";
            return null;
        }
        if (d.Id is "CS0246" or "CS0103")
        {
            var m = System.Text.RegularExpressions.Regex.Match(msg, @"name '([^']+)'");
            if (!m.Success) return null;
            var name = m.Groups[1].Value;
            if (d.Id == "CS0246")
            {
                var homes = index.types.TryGetValue(name, out var a) ? a : index.types.TryGetValue(name + "Attribute", out var b) ? b : null;
                if (homes != null) return "It is in " + string.Join(" and ", homes) + ": add `using " + homes[0] + ";`.";
            }
            if (index.members.TryGetValue(name, out var holders)) return "It is in " + string.Join(" and ", holders) + ": add `using static " + holders[0] + ";`.";
            if (index.types.TryGetValue(name, out var ts)) return "It is in " + string.Join(" and ", ts) + ": add `using " + ts[0] + ";`.";
            // Cocos is a namespace, not a global using
            var cc = CcNames();
            if (cc.types.Contains(name) || cc.types.Contains(name + "Attribute")) return "It is in cc: add `using cc;` at the top of the file.";
            if (cc.globals.Contains(name)) return "It is in cc.Globals: add `using static cc.Globals;` at the top of the file.";
        }
        return null;
    }

    /// <summary>
    /// Global usings of every C# script: System, collections, LINQ and tasks only. Cocos is a
    /// namespace like UnityEngine: scripts write `using cc;` (types) and `using static cc.Globals;`
    /// (director, log, tween...). A name both System and cc define (EventHandler, ValueType) is then
    /// ambiguous (CS0104) only where it is used; the error hint says how to pick one.
    /// </summary>
    public static string GlobalUsings()
    {
        if (_globalUsings != null) return _globalUsings;
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> Global usings of C# scripts for Cocos (extensions/csharp).");
        sb.AppendLine("// Cocos is not global: write `using cc;` and `using static cc.Globals;` in the scripts that use it.");
        sb.AppendLine("global using System;");
        sb.AppendLine("global using System.Collections.Generic;");
        sb.AppendLine("global using System.Linq;");
        sb.AppendLine("global using System.Threading.Tasks;");
        _globalUsings = sb.ToString();
        return _globalUsings;
    }

    static HashSet<string> _ccTypes;
    static HashSet<string> _ccGlobals;

    /// <summary>Type names of namespace cc and member names of cc.Globals: for "add `using cc;`" hints.</summary>
    static (HashSet<string> types, HashSet<string> globals) CcNames()
    {
        if (_ccTypes != null) return (_ccTypes, _ccGlobals);
        var types = new HashSet<string>(StringComparer.Ordinal);
        var globals = new HashSet<string>(StringComparer.Ordinal);
        try
        {
            var comp = CSharpCompilation.Create("probe", Array.Empty<SyntaxTree>(), References());
            var ccNs = comp.GlobalNamespace.GetNamespaceMembers().FirstOrDefault(n => n.Name == "cc");
            if (ccNs != null)
            {
                foreach (var t in ccNs.GetTypeMembers()) if (t.DeclaredAccessibility == Accessibility.Public) types.Add(t.Name);
                var g = ccNs.GetTypeMembers("Globals").FirstOrDefault();
                if (g != null) foreach (var m in g.GetMembers()) if (m.DeclaredAccessibility == Accessibility.Public && m.IsStatic) globals.Add(m.Name);
            }
        }
        catch
        {
            // no hints
        }
        _ccTypes = types;
        _ccGlobals = globals;
        return (types, globals);
    }

    SyntaxTree Parse(string path)
    {
        var info = new FileInfo(path);
        if (_trees.TryGetValue(path, out var c) && c.time == info.LastWriteTimeUtc && c.size == info.Length) return c.tree;
        string text;
        // the IDE may still hold the file for a moment
        for (var attempt = 0; ; attempt++)
        {
            try { text = File.ReadAllText(path); break; }
            catch (IOException) when (attempt < 5) { Thread.Sleep(40); }
        }
        var tree = CSharpSyntaxTree.ParseText(text, ParseOptions, path, Encoding.UTF8);
        _trees[path] = (info.LastWriteTimeUtc, info.Length, tree);
        return tree;
    }

    public static IEnumerable<string> SourceFiles(string root)
    {
        var assets = Path.Combine(root, "assets");
        if (!Directory.Exists(assets)) return Array.Empty<string>();
        return Directory.EnumerateFiles(assets, "*.cs", SearchOption.AllDirectories)
            .Where(p => !p.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Any(s => s.StartsWith(".")))
            .OrderBy(p => p, StringComparer.OrdinalIgnoreCase);
    }

    /// <summary>Compiles the C# scripts of a Cocos project and emits TypeScript next to them.</summary>
    public CompileResult Compile(string root, bool write, IEnumerable<string> explicitFiles = null)
    {
        var sw = System.Diagnostics.Stopwatch.StartNew();
        var result = new CompileResult();
        var files = (explicitFiles ?? SourceFiles(root)).Select(Path.GetFullPath).ToList();
        foreach (var k in _trees.Keys.ToList()) if (!files.Contains(k, StringComparer.OrdinalIgnoreCase)) _trees.Remove(k);
        var trees = files.Select(Parse).ToList();
        // the project's TypeScript, seen through declaration-only stubs (never emitted)
        var (tsTree, hidden) = WithoutUserTypes(TsTree(root), trees);
        var usingsTree = CSharpSyntaxTree.ParseText(GlobalUsings(tsTree), ParseOptions, "GlobalUsings.g.cs");
        var options = new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Disable, allowUnsafe: false)
            .WithSpecificDiagnosticOptions(Silenced.ToDictionary(id => id, _ => ReportDiagnostic.Suppress));
        var comp = CSharpCompilation.Create("CocosScripts", trees.Append(usingsTree).Append(tsTree), References(), options);
        foreach (var h in hidden)
            result.Diagnostics.Add(new Diag(TsBindingsRel, 1, 1, "info", "CSX3010", $"The C# class {h} hides the project's TypeScript export {h}: C# scripts see the C# one."));

        (Dictionary<string, List<string>>, Dictionary<string, List<string>>)? stubIndex = null;
        foreach (var d in comp.GetDiagnostics())
        {
            if (d.Severity < DiagnosticSeverity.Warning || d.IsSuppressed) continue;
            var diag = ToDiag(d, root);
            // a problem inside the generated stubs: report it, it doesn't block the scripts
            if (d.Location.SourceTree == tsTree) diag = diag with { Severity = "warning", Message = "TS interop stub: " + diag.Message };
            else if (d.Id is "CS0104" or "CS0246" or "CS0103" or "CS0616")
            {
                stubIndex ??= StubIndex(tsTree);
                var hint = Hint(d, stubIndex.Value);
                if (hint != null) diag = diag with { Message = diag.Message.TrimEnd() + (diag.Message.TrimEnd().EndsWith(".") ? " " : ". ") + hint };
            }
            result.Diagnostics.Add(diag);
        }

        Sym.TsTree = tsTree;
        var ctx = new ProjectContext(comp, trees, root);
        foreach (var tree in trees)
        {
            var path = tree.FilePath;
            var fo = new FileOutput { CsPath = path, TsPath = Path.ChangeExtension(path, ".ts") };
            var fileErrors = result.Diagnostics.Any(d => d.Severity == "error" && string.Equals(Path.GetFullPath(Path.Combine(root, d.File)), path, StringComparison.OrdinalIgnoreCase));
            try
            {
                var em = new Emitter(ctx, comp.GetSemanticModel(tree), tree);
                fo.Ts = em.EmitFile();
                foreach (var d in em.Diagnostics) result.Diagnostics.Add(d with { File = Rel(root, d.File) });
                if (em.Diagnostics.Any(d => d.Severity == "error")) fileErrors = true;
            }
            catch (Exception e)
            {
                fileErrors = true;
                result.Diagnostics.Add(new Diag(Rel(root, path), 1, 1, "error", "CSX0000", "Internal transpiler error: " + e.Message + " " + e.StackTrace?.Split('\n').FirstOrDefault()?.Trim()));
            }
            fo.HasErrors = fileErrors;
            result.Files.Add(fo);
        }

        // a .ts written by the user must never be overwritten
        foreach (var f in result.Files)
        {
            if (File.Exists(f.TsPath) && !IsGenerated(f.TsPath))
            {
                f.HasErrors = true;
                result.Diagnostics.Add(new Diag(Rel(root, f.CsPath), 1, 1, "error", "CSX0001", $"{Path.GetFileName(f.TsPath)} already exists and was not generated from {Path.GetFileName(f.CsPath)}. Rename one of them."));
            }
        }

        if (write)
        {
            foreach (var f in result.Files)
            {
                if (f.HasErrors) { if (File.Exists(f.TsPath)) result.Kept.Add(f.TsPath); continue; }
                var old = File.Exists(f.TsPath) ? File.ReadAllText(f.TsPath) : null;
                if (old == f.Ts) { result.Unchanged.Add(f.TsPath); continue; }
                File.WriteAllText(f.TsPath, f.Ts, new UTF8Encoding(false));
                result.Written.Add(f.TsPath);
            }
        }
        var assets = Path.Combine(root, "assets");
        if (Directory.Exists(assets))
            foreach (var ts in Directory.EnumerateFiles(assets, "*.ts", SearchOption.AllDirectories))
                if (!File.Exists(Path.ChangeExtension(ts, ".cs")) && IsGenerated(ts)) result.Orphans.Add(ts);
        result.Ms = sw.ElapsedMilliseconds;
        return result;
    }

    public static bool IsGenerated(string tsPath)
    {
        try
        {
            using var r = new StreamReader(tsPath);
            var first = r.ReadLine();
            return first != null && first.StartsWith(HeaderPrefix, StringComparison.Ordinal);
        }
        catch { return false; }
    }

    static string Rel(string root, string path)
    {
        try
        {
            var full = Path.GetFullPath(path);
            var r = Path.GetRelativePath(root, full);
            return r.StartsWith("..") ? full : r.Replace('\\', '/');
        }
        catch { return path; }
    }

    static Diag ToDiag(Diagnostic d, string root)
    {
        var span = d.Location.GetLineSpan();
        var file = d.Location.IsInSource ? Rel(root, span.Path) : "";
        return new Diag(file, span.StartLinePosition.Line + 1, span.StartLinePosition.Character + 1,
            d.Severity == DiagnosticSeverity.Error ? "error" : "warning", d.Id, d.GetMessage());
    }
}
