/**
 * TS interop paths, without the TypeScript compiler (main.ts uses them on every asset event):
 * which asset dbs are read, which files are C# output, and the exclude list.
 */
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

/** First characters of a .ts written by the transpiler. */
export const GENERATED_FROM_CS = '// <auto-generated> from ';

/** The project setting holding the exclude list (Editor.Profile project scope, package csharp). */
export const EXCLUDE_KEY = 'tsInterop.exclude';

export interface InteropRoot {
    /** Asset db name: 'assets' or the extension's package name. */
    db: string;
    /** Absolute folder of the db. */
    dir: string;
}

/** Creator's global extensions folder (%USERPROFILE%\.CocosCreator\extensions). */
export function globalExtensionsDir(): string {
    return path.join(os.homedir(), '.CocosCreator', 'extensions');
}

/**
 * The asset dbs to read: db://assets plus each extension mounting one (except the C# extension),
 * from the project's extensions/ and, unless `globalDir` is null, the global extensions folder.
 * A project extension wins over a global one with the same name.
 */
export function interopRoots(projectRoot: string, globalDir: string | null = globalExtensionsDir()): InteropRoot[] {
    const roots: InteropRoot[] = [{ db: 'assets', dir: path.join(projectRoot, 'assets') }];
    const dirs = [path.join(projectRoot, 'extensions')];
    if (globalDir && path.resolve(globalDir) !== path.resolve(dirs[0])) dirs.push(globalDir);
    for (const extDir of dirs) {
        let exts: fs.Dirent[] = [];
        try {
            exts = fs.readdirSync(extDir, { withFileTypes: true });
        } catch (e) {
            exts = [];
        }
        for (const e of exts) {
            if (!e.isDirectory()) continue;
            try {
                const pj = JSON.parse(fs.readFileSync(path.join(extDir, e.name, 'package.json'), 'utf8'));
                const mount = pj && pj.contributions && pj.contributions['asset-db'] && pj.contributions['asset-db'].mount;
                if (!mount || typeof mount.path !== 'string' || !pj.name || pj.name === 'csharp') continue;
                if (roots.some((r) => r.db === pj.name)) continue;
                roots.push({ db: pj.name, dir: path.join(extDir, e.name, mount.path) });
            } catch (x) {
                // not an extension
            }
        }
    }
    return roots;
}

/** Whether an asset url is TypeScript the interop reads (before the exclude list and the C#-output check). */
export function isInteropTsUrl(url: string, dbs: string[]): boolean {
    if (typeof url !== 'string' || !/\.ts$/i.test(url) || /\.d\.ts$/i.test(url)) return false;
    const m = /^db:\/\/([^/]+)\//.exec(url);
    return !!m && dbs.indexOf(m[1]) >= 0;
}

/** Cleans the exclude list (one glob per line or an array). */
export function normalizeExclude(v: unknown): string[] {
    const list = Array.isArray(v) ? v : typeof v === 'string' ? v.split(/\r?\n/) : [];
    const out: string[] = [];
    for (const s of list) {
        if (typeof s !== 'string') continue;
        const t = s.trim().replace(/\\/g, '/');
        if (t && !t.startsWith('#') && out.indexOf(t) < 0) out.push(t);
    }
    return out;
}

/**
 * A glob of the exclude list as a test on "assets/Tests/Foo.ts" / "db://assets/Tests/Foo.ts":
 * `*` stays in a folder, `**` crosses folders, a path without wildcards is a folder or a file.
 */
export function globToRegExp(glob: string): RegExp {
    let g = glob.trim().replace(/\\/g, '/');
    if (!/[*?]/.test(g)) g = g.replace(/\/+$/, '') + '/**'; // a folder (or file) without wildcards
    let re = '';
    for (let i = 0; i < g.length; i++) {
        const c = g[i];
        if (c === '*') {
            if (g[i + 1] === '*') {
                i++;
                if (g[i + 1] === '/') {
                    re += '(?:.*/)?'; // **/ : any folders, or none
                    i++;
                } else re += '.*';
            } else re += '[^/]*';
        } else if (c === '?') re += '[^/]';
        else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
    }
    return new RegExp('^' + re + '$', 'i');
}

/** Whether a module (by db url and project-relative path) is excluded. Plain names also match the exact file. */
export function isExcluded(exclude: string[], dbUrl: string, relPath: string): boolean {
    for (const g of exclude) {
        if (!g || !g.trim() || g.trim().startsWith('#')) continue;
        const re = globToRegExp(g);
        const plain = g.trim().replace(/\\/g, '/');
        if (re.test(dbUrl) || re.test(relPath) || plain === dbUrl || plain === relPath) return true;
    }
    return false;
}
