/**
 * Pure helpers of the C# extension: paths between .cs and .ts, script templates,
 * the IDE project, diagnostics text. No editor APIs, so they are unit-tested.
 */

export const GENERATED_PREFIX = '// <auto-generated> from ';

/** db://assets/a/B.cs -> db://assets/a/B.ts */
export function tsUrlOf(csUrl: string): string {
    return csUrl.replace(/\.cs$/i, '.ts');
}

export function isAssetsCs(url: string | undefined | null): boolean {
    return !!url && /^db:\/\/assets\/.+\.cs$/i.test(url);
}

/** Absolute path inside <project>/assets -> db://assets/... (null outside). */
export function toDbUrl(projectRoot: string, abs: string): string | null {
    const norm = (p: string) => p.replace(/\\/g, '/').replace(/\/+$/, '');
    const assets = norm(projectRoot) + '/assets/';
    const a = norm(abs);
    if (a.toLowerCase().indexOf(assets.toLowerCase()) !== 0) return null;
    return 'db://assets/' + a.slice(assets.length);
}

/** A valid C# class name from a file name: "my enemy-2.cs" -> "MyEnemy2". */
export function classNameFromFile(fileName: string): string {
    const base = fileName.replace(/\.cs$/i, '');
    const parts = base.split(/[^A-Za-z0-9_]+/).filter((p) => p.length);
    let name = parts.map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1))).join('');
    if (!name) name = 'NewComponent';
    if (/^[0-9]/.test(name)) name = '_' + name;
    return name;
}

/**
 * The C# Script (component) template. No [ccclass]: components get @ccclass automatically,
 * and public fields of serializable types are saved and shown in the Inspector.
 */
export function componentTemplate(className: string): string {
    return [
        'using cc;',
        'using static cc.Globals;',
        '',
        `public class ${className} : Component`,
        '{',
        '    // Public fields are saved and shown in the Inspector.',
        '    public double speed = 1;',
        '',
        '    protected override void start()',
        '    {',
        '    }',
        '',
        '    protected override void update(double dt)',
        '    {',
        '    }',
        '}',
        '',
    ].join('\n');
}

/** A plain C# class (not a component). */
export function classTemplate(className: string): string {
    return [`public class ${className}`, '{', '}', ''].join('\n');
}

/**
 * When a new script is renamed before it is edited, its class follows the file name
 * (the template text for the old name is replaced by the one for the new name).
 */
export function renamedTemplate(content: string, oldFile: string, newFile: string): string | null {
    const oldName = classNameFromFile(oldFile);
    const newName = classNameFromFile(newFile);
    if (oldName === newName) return null;
    const norm = (s: string) => s.replace(/\r\n/g, '\n');
    if (norm(content) === norm(componentTemplate(oldName))) return componentTemplate(newName);
    if (norm(content) === norm(classTemplate(oldName))) return classTemplate(newName);
    return null;
}

export interface Diagnostic {
    file: string;
    line: number;
    column: number;
    severity: 'error' | 'warning' | 'info';
    code: string;
    message: string;
}

/** Roslyn-style text: assets/Scripts/Player.cs(12,5): error CS0103: ... */
export function formatDiagnostic(d: Diagnostic): string {
    return `${d.file}(${d.line},${d.column}): ${d.severity} ${d.code}: ${d.message}`;
}

export interface CsprojOptions {
    /** The Cocos project folder. */
    projectRoot: string;
    /** Absolute path of Cocos.Bindings.dll. */
    bindingsDll: string;
    /** Absolute path of the global usings file. */
    globalUsings: string;
    targetFramework: string;
}

function relOrAbs(from: string, to: string): string {
    const f = from.replace(/\\/g, '/').replace(/\/+$/, '') + '/';
    const t = to.replace(/\\/g, '/');
    return t.toLowerCase().indexOf(f.toLowerCase()) === 0 ? t.slice(f.length) : t;
}

/** The IDE project at the project root (IntelliSense and errors in VS Code / Rider / Visual Studio). */
export function csprojText(o: CsprojOptions): string {
    const dll = relOrAbs(o.projectRoot, o.bindingsDll);
    const usings = relOrAbs(o.projectRoot, o.globalUsings);
    // TS interop stubs: written next to the global usings (temp/csharp/TsBindings.g.cs)
    const tsBindings = usings.replace(/[^/]*$/, 'TsBindings.g.cs');
    return [
        '<Project Sdk="Microsoft.NET.Sdk">',
        '  <!-- Generated by the C# extension (extensions/csharp) for IntelliSense: C# scripts in assets/',
        '       are transpiled to TypeScript by the extension; this project is never built for the game. -->',
        '  <PropertyGroup>',
        `    <TargetFramework>${o.targetFramework}</TargetFramework>`,
        '    <OutputType>Library</OutputType>',
        '    <LangVersion>latest</LangVersion>',
        '    <Nullable>disable</Nullable>',
        '    <ImplicitUsings>disable</ImplicitUsings>',
        '    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>',
        '    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>',
        '    <NoWarn>$(NoWarn);CS0108;CS0114;CS0169;CS0649;CS0414;CS0067;CS8618;CS1998;CS0219</NoWarn>',
        '  </PropertyGroup>',
        '  <ItemGroup>',
        '    <Compile Include="assets/**/*.cs" />',
        `    <Compile Include="${usings}" Link="GlobalUsings.g.cs" />`,
        `    <Compile Include="${tsBindings}" Link="TsBindings.g.cs" Condition="Exists('${tsBindings}')" />`,
        '  </ItemGroup>',
        '  <ItemGroup>',
        '    <Reference Include="Cocos.Bindings">',
        `      <HintPath>${dll}</HintPath>`,
        '    </Reference>',
        '  </ItemGroup>',
        '</Project>',
        '',
    ].join('\n');
}

/** Major version of the newest .NET SDK in `dotnet --list-sdks` output (net9.0 at least). */
export function targetFrameworkFromSdks(listSdks: string): string {
    let best = 9;
    for (const line of listSdks.split(/\r?\n/)) {
        const m = /^(\d+)\.\d+\.\d+/.exec(line.trim());
        if (m) best = Math.max(best, Number(m[1]));
    }
    return 'net' + Math.min(best, 9) + '.0';
}
