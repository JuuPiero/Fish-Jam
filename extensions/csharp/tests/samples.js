/** Spread or rest syntax (`...x`) in TypeScript, strings aside: Cocos' loose builds lose data with it. */
function hasSpread(text) {
    const tsc = require('typescript');
    let found = false;
    const visit = (n) => {
        if (tsc.isSpreadElement(n) || tsc.isSpreadAssignment(n) || ((tsc.isParameter(n) || tsc.isBindingElement(n)) && n.dotDotDotToken)) found = true;
        else tsc.forEachChild(n, visit);
    };
    visit(tsc.createSourceFile('x.ts', text, tsc.ScriptTarget.Latest, true));
    return found;
}
