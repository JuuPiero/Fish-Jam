// the server protocol the editor uses: ready event, then one JSON line per request
async function serverCheck() {
    console.log('\n# server');
    const { spawn } = require('child_process');
    const p = spawn('dotnet', [tool, 'server'], { cwd: path.dirname(tool) });
    let buf = '';
    const lines = [];
    const waiters = [];
    p.stdout.setEncoding('utf8');
    p.stdout.on('data', (d) => {
        buf += d;
        let i;
        while ((i = buf.indexOf('\n')) >= 0) {
            const l = buf.slice(0, i).trim();
            buf = buf.slice(i + 1);
            if (!l) continue;
            const w = waiters.shift();
            if (w) w(JSON.parse(l));
            else lines.push(JSON.parse(l));
        }
    });
    const next = () => new Promise((r) => (lines.length ? r(lines.shift()) : waiters.push(r)));
    const ready = await next();
    ok(ready.event === 'ready', 'server says ready');
    p.stdin.write(JSON.stringify({ id: 7, cmd: 'compile', root: samples, write: false }) + '\n');
    const r1 = await next();
    const csCount = walk(path.join(samples, 'assets'), '.cs').length;
    ok(r1.id === 7 && r1.ok && r1.files === csCount && r1.errors === 0, 'compile request: ' + JSON.stringify({ files: r1.files, errors: r1.errors, ms: r1.ms }));
    p.stdin.write(JSON.stringify({ id: 8, cmd: 'compile', root: samples, write: false }) + '\n');
    const r2 = await next();
    ok(r2.ok && r2.ms <= r1.ms, 'second compile reuses parsed files (' + r1.ms + ' ms -> ' + r2.ms + ' ms)');
    p.stdin.write(JSON.stringify({ id: 9, cmd: 'usings' }) + '\n');
    const u = await next();
    ok(u.ok && /global using System;/.test(u.text) && !/^global using (static )?cc/m.test(u.text) && !/global::cc\./.test(u.text), 'global usings: System only, cc is a namespace scripts import (`using cc;`)');
    p.stdin.write(JSON.stringify({ id: 12, cmd: 'usings', root: samples }) + '\n');
    const u2 = await next();
    ok(u2.ok && /global using static ProjectExports;/.test(u2.text) && !/ProjectExports/.test(u.text) && !/Ext\./.test(u2.text), 'usings of a project add `using static ProjectExports`, never an extension namespace');
    p.stdin.write(JSON.stringify({ id: 10, cmd: 'eval', code: '1' }) + '\n');
    const bad = await next();
    ok(bad.ok === false, 'unknown commands are refused');
    p.stdin.write(JSON.stringify({ id: 11, cmd: 'exit' }) + '\n');
    await next();
    await new Promise((r) => p.on('close', r));
    ok(true, 'server exits');
}

